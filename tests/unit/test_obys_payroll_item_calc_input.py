def _item_css():
    src = MODULE.read_text(encoding="utf-8")
    start = src.index("const ITEM_CSS")
    return src[start:src.index("</style>", start)]


def _selectors(css):
    body = css.split("@media (max-width:480px){", 1)[1]
    return [sel.strip() for block in re.findall(r"([^{}]+)\{[^{}]*\}", body) for sel in block.split(",")]


def test_item_css_tr_td_selectors_are_scoped_to_edit_rows():
    css = _item_css()
    tr_td = [s for s in _selectors(css) if re.search(r"\b(tr|td)\b", s)]
    assert tr_td
    for sel in tr_td:
        assert ".pi-row" in sel or ".pi-calc" in sel, sel
    assert ".payroll-item-table td{" not in css and "tbody tr{" not in css and "[data-calc-row]" not in css


