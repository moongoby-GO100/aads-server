from app.services import yeoljeong_payroll_pdf as pdf


def _pay(item):
    return pdf._clean_item_list([item], pdf.PAY_ITEM_CODES, "지급 항목", with_note=True)[0]


def _base(**extra):
    return {"code": "base", "label": "기본급", "amount": 87500, "calc_note": "", **extra}


def test_calc_preserved_and_minute_conversion_matches():
    item = _pay(_base(calc={"rate": 12500, "qty": 420, "unit": "minute"}))
    assert item["calc"] == {"rate": 12500, "qty": 420, "unit": "minute"}
    assert "calc_override" not in item
    assert pdf.calc_amount(item["calc"]) == 87500


def test_calc_match_hour_has_no_override_and_decimal_qty():
    item = _pay(_base(amount=18750, calc={"rate": 12500, "qty": "1.5", "unit": "hour"}))
    assert item["calc"]["qty"] == 1.5 and "calc_override" not in item


def test_calc_mismatch_sets_override_and_keeps_amount():
    item = _pay(_base(amount=90000, calc={"rate": 12500, "qty": 420, "unit": "minute"}))
    assert item["calc_override"] is True and item["amount"] == 90000


def test_calc_note_autogenerated_when_blank_and_admin_note_kept():
    item = _pay(_base(amount=87500, calc={"rate": 12500, "qty": 7, "unit": "hour"}))
    assert item["calc_note"] == "시급 12,500원 × 7시간"
    kept = _pay(_base(amount=87500, calc_note="관리자 메모", calc={"rate": 12500, "qty": 7, "unit": "hour"}))
    assert kept["calc_note"] == "관리자 메모"


