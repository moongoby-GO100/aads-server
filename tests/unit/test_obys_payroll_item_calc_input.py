def test_all_edit_row_controls_get_44px_in_480_rule():
    css = _item_css()
    rule = re.search(r"([^{}]*select)\{([^{}]*min-height:44px[^{}]*)\}", css)
    assert rule, "44px 규칙 없음"
    selectors = [s.strip() for s in rule.group(1).split(",")]
    # 편집 행(.pi-row)의 select/input/button 과 계산 행(.pi-calc)의 input/select
    for cell, control in (("pi-code", "select"), ("pi-label", "input"), ("pi-amount", "input"), ("pi-note", "input"), ("pi-del", ".btn")):
        assert any(f"tr.pi-row>td.{cell} {control}" in s for s in selectors), (cell, control)
    assert any("tr.pi-calc input" in s for s in selectors) and any("tr.pi-calc select" in s for s in selectors)
    # 렌더된 모든 편집 행 컨트롤은 인라인 min-height:44px 도 갖는다
    src = MODULE.read_text(encoding="utf-8")
    for key in ('data-k="code"', 'data-k="label"', 'data-k="amount"', 'data-k="calc_note"', "data-item-del", 'data-k="calc_rate"', 'data-k="calc_qty"', 'data-k="calc_unit"'):
        line = next(l for l in src.splitlines() if key in l and "<" in l)
        assert "min-height:44px" in line, key
