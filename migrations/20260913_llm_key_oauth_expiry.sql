-- OAuth 토큰 만료 시각.
--
-- 러너는 CLI 호출 직전에 토큰을 고르지만 남은 수명을 알 방법이 없었다. 토큰
-- 수명은 8시간인데 단일 CLI 호출은 MAX_RUNTIME(2시간)까지 간다. 만료가 임박한
-- 토큰으로 긴 작업을 시작하면 도중에 401 로 죽는다(실측: 최근 7일 62건 중
-- 5건이 8시간을 넘었고 최대 20시간).
--
-- 토큰 자체는 불투명 문자열이라 만료를 읽을 수 없다. 슬롯 자격증명 파일에는
-- 있지만 그 파일은 호스트에 있고 앱 컨테이너에서 보이지 않는다. 그래서
-- 갱신 시점에 keeper 가 이 컬럼에 기록한다.
ALTER TABLE llm_api_keys ADD COLUMN IF NOT EXISTS oauth_expires_at timestamptz;
