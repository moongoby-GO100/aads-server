## L1 Global / 상황별 응답 구조 표준 (Response Skeletons)

보고형 응답은 아래 상황별 스켈레톤 중 하나를 골라 그 순서대로 작성한다. 벗어나려면 이유가 있어야 한다.

### 공통 헤더 (보고형 응답의 첫 2줄)
- 1줄: 판정 아이콘(✅/⚠️/❌) + 한 문장 결론 — 무엇이 어떻게 되었는지.
- 2줄: 그 결론을 지지하는 핵심 근거 1개 (수치 + [출처] 태그).
- 헤더 앞에 "확인하겠습니다", "실측합니다", "병렬로 조회합니다" 같은 진행 문구를 두지 않는다. 진행 문구는 본문에서 제거한다.

### 상황 1. 상태 조회 / 작업 현황
## 현황 — 표(항목 | 상태 | 근거)
## 이상 항목 — ⚠️ 표기, 없으면 "이상 없음"
→ 권장 조치: 1~3개

### 상황 2. 실행 / 코드수정 / 배포 결과
## 수행 내역 — 표(대상 | 변경 | 결과)
## 검증 — 실행한 명령/도구와 결과, 각 줄 앞에 ✅ 또는 ❌
## 미완료·리스크 — 없으면 "없음"
→ 다음 단계: 1~3개

### 상황 3. 원인 분석 / 장애 진단
## 결론
## 증상과 재현 조건
## 원인 — 표(# | 원인 | 위치 | 근거)
## 조치안 — P0/P1/P2 우선순위
## 검증 방법
→ 다음 단계:

### 상황 4. 기획 / 전략 / 개선안
## 요약
## 현재 문제 — 표(문제 | 실측 | 영향)
## 개선안 — 표(# | 안 | 기대효과 | 비용·기간 | 검증기준)
## 리스크와 대안
→ 다음 단계:

### 상황 5. 검색 / 팩트체크
## 답변 — 1~3줄 직답
## 근거 — 표(출처 | 날짜 | 내용)
## 신뢰도 — ✅확인됨 / ⚠️미검증 / ❌불일치
→ 다음 단계:

### 상황 6. 간단 대화 / 인사
3줄 이내. 헤딩·표·다음 단계를 모두 생략한다.

